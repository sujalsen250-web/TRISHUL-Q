"""PDF export for TRISHUL-Q (admin registration details).

Every PDF carries the TRISHUL-Q header + trident motif.  Built with ReportLab
(pure-Python) so no external binary is required.
"""
from __future__ import annotations

import io
from datetime import datetime, timezone

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (Paragraph, SimpleDocTemplate, Spacer, Table,
                                TableStyle)

from . import config

_INK = colors.HexColor("#0d1220")
_ACCENT = colors.HexColor("#5b6cff")
_MUTED = colors.HexColor("#5a6478")


def _styles():
    ss = getSampleStyleSheet()
    return {
        "title": ParagraphStyle("tq-title", parent=ss["Title"], fontName="Helvetica-Bold",
                                fontSize=22, textColor=_INK, spaceAfter=2),
        "sub": ParagraphStyle("tq-sub", parent=ss["Normal"], fontSize=9.5,
                              textColor=_MUTED, alignment=1),
        "h2": ParagraphStyle("tq-h2", parent=ss["Heading2"], fontSize=13,
                             textColor=_ACCENT),
        "body": ParagraphStyle("tq-body", parent=ss["Normal"], fontSize=9.5,
                               textColor=_INK),
        "cell": ParagraphStyle("tq-cell", parent=ss["Normal"], fontSize=8),
    }


def _header(canvas, doc):
    canvas.saveState()
    canvas.setFillColor(_INK)
    canvas.rect(0, A4[1] - 26 * mm, A4[0], 26 * mm, stroke=0, fill=1)
    # trident motif (three prongs = three detection layers)
    cx, cy = 22 * mm, A4[1] - 13 * mm
    canvas.setStrokeColor(_ACCENT)
    canvas.setLineWidth(2.2)
    for dx in (-3 * mm, 0, 3 * mm):
        canvas.line(cx + dx, cy - 4 * mm, cx + dx, cy + 5 * mm)
    canvas.setLineWidth(2.6)
    canvas.line(cx, cy - 6 * mm, cx, cy - 4 * mm)
    canvas.line(cx - 3 * mm, cy - 4 * mm, cx + 3 * mm, cy - 4 * mm)
    canvas.setFillColor(colors.white)
    canvas.setFont("Helvetica-Bold", 20)
    canvas.drawString(cx + 12 * mm, cy - 2 * mm, config.APP_NAME)
    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(colors.HexColor("#b9c1d6"))
    canvas.drawString(cx + 12 * mm, cy - 6 * mm, config.APP_FULL_NAME)
    canvas.setFont("Helvetica", 7.5)
    canvas.drawRightString(A4[0] - 18 * mm, cy - 2 * mm,
                           datetime.now(timezone.utc).strftime("%d/%m/%Y %H:%M UTC"))
    canvas.setStrokeColor(_ACCENT)
    canvas.setLineWidth(1)
    canvas.line(0, A4[1] - 26 * mm, A4[0], A4[1] - 26 * mm)
    canvas.restoreState()


def admin_registration_pdf(requests: list[dict], subtitle: str = "Admin registration details") -> bytes:
    """Render a list of admin-registration records to a PDF (bytes)."""
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, topMargin=34 * mm,
                            bottomMargin=18 * mm, leftMargin=16 * mm, rightMargin=16 * mm,
                            title=f"{config.APP_NAME} - {subtitle}",
                            author=config.APP_NAME)
    st = _styles()
    story = [
        Paragraph("Admin Registration Details", st["title"]),
        Paragraph(subtitle, st["sub"]),
        Spacer(1, 8 * mm),
        Paragraph(f"Records: {len(requests)}", st["h2"]),
        Spacer(1, 3 * mm),
    ]
    header = ["Request ID", "Full name", "Email", "Phone", "Department",
              "Dept ID", "Gender", "Status", "Created"]
    rows = [header]
    for r in requests:
        rows.append([
            r.get("request_id", ""), r.get("full_name", ""), r.get("email", ""),
            r.get("phone", ""), r.get("department", ""), r.get("department_id", ""),
            r.get("gender", ""), r.get("status", ""), (r.get("created_at", "") or "")[:10],
        ])
    table = Table(rows, repeatRows=1, colWidths=[
        24 * mm, 26 * mm, 40 * mm, 22 * mm, 24 * mm, 20 * mm, 14 * mm, 20 * mm, 20 * mm])
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), _ACCENT),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 7.6),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#c8cedd")),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1),
         [colors.white, colors.HexColor("#f2f4fa")]),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 3),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
    ]))
    story.append(table)
    story.append(Spacer(1, 6 * mm))
    story.append(Paragraph(
        "Generated by the TRISHUL-Q Super Admin panel (localhost only). "
        "Confidential -- handle per your organisation's data-protection policy.",
        st["body"]))
    doc.build(story, onFirstPage=_header, onLaterPages=_header)
    return buf.getvalue()
